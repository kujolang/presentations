// Checked-in optional browser module keeps native Kujo builds offline.
import { build } from 'esbuild';
import { mkdirSync, copyFileSync } from 'node:fs';
mkdirSync('vendor/motion',{recursive:true});
await build({stdin:{contents:'export { animate } from "motion/mini";',resolveDir:process.cwd()},bundle:true,minify:true,format:'esm',platform:'browser',target:'es2022',outfile:'vendor/motion/motion-mini.js',banner:{js:'/* Motion 13.4.6 (MIT). Generated by npm run bundle:motion. */'}});
copyFileSync('node_modules/motion/LICENSE.md','vendor/motion/LICENSE.md');
copyFileSync('node_modules/framer-motion/LICENSE.md','vendor/motion/LICENSE-framer-motion.md');

await build({stdin:{contents:'export { animate, stagger, frame } from "motion";',resolveDir:process.cwd()},bundle:true,minify:true,format:'esm',platform:'browser',target:'es2022',outfile:'vendor/motion/motion-hybrid.js',banner:{js:'/* Motion 13.4.6 (MIT). Generated by npm run bundle:motion. */'}});
